import {
  automaticQualificationFor,
  calculateLeadScore,
  effectiveQualificationFor,
} from "@/lib/scoring";
import type { Lead, WebsiteAudit } from "@/types/lead";

function makeSampleLead(
  input: Omit<Lead, "score" | "automaticQualification" | "rawImportedData">,
): Lead {
  const score = calculateLeadScore(input);
  const automaticQualification = automaticQualificationFor({
    hasWebsite: input.hasWebsite,
    audit: input.audit,
    score,
  });
  return {
    ...input,
    score,
    automaticQualification,
    qualificationStatus: effectiveQualificationFor(
      input.manualDecision,
      automaticQualification,
    ),
    rawImportedData: {
      name: input.name,
      address: input.address,
      phone: input.phone ?? null,
      rating: input.rating?.toString() ?? null,
      total_ratings: input.totalRatings?.toString() ?? null,
      website: input.website ?? null,
      type: input.category,
      source_file: input.sourceFile,
      scrape_date: input.scrapeDate ?? null,
    },
  };
}

